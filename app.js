function nav(current) {
  return `<aside class="step-sidebar" aria-label="Parcours en six étapes">
    <h2>Votre parcours</h2>
    <nav class="step-nav">${steps.map(s => `<a href="etape-${s.id}.html" ${s.id === current ? 'aria-current="page"' : ''}><span class="nav-num">${s.id}</span><span>${s.title}</span></a>`).join("")}</nav>
  </aside>`;
}

function resources(items) {
  return items.map(([type, name, desc, url]) => `<a class="resource-card" href="${url}" target="_blank" rel="noopener noreferrer"><span class="resource-type">${type}</span><strong>${name} ↗</strong><span>${desc}</span></a>`).join("");
}

function renderStep(step) {
  const previous = step.id > 1 ? `<a class="button secondary" href="etape-${step.id - 1}.html">← Étape précédente</a>` : `<a class="button secondary" href="index.html">← Parcours</a>`;
  const next = step.id < 6 ? `<a class="button" href="etape-${step.id + 1}.html">Passer à l’étape ${step.id + 1} →</a>` : `<a class="button" href="index.html">Revoir le parcours</a>`;
  const image = `assets/mission-${step.id}.webp`;
  const imageAlts = {
    1: "Entrée d’un magasin d’ameublement bleu et jaune à explorer",
    2: "Cible, loupe et outils pour cadrer une question de veille",
    3: "Sources variées rassemblées pour commencer la collecte",
    4: "Flux automatisé reliant ordinateur, données et notification",
    5: "Informations, graphiques et tendances croisés sur une table",
    6: "Planche de recommandations et maquette d’un espace aménagé"
  };
  return `<main id="step-root" class="step-shell">
    ${nav(step.id)}
    <article class="step-content">
      <header class="step-hero">
        <div class="step-hero-copy">
          <div class="step-meta"><span>Étape ${step.id}/6</span><span>${step.course}</span></div>
          <h1>${step.title}</h1>
          <p>${step.mission}</p>
        </div>
        <div class="step-hero-media"><img src="${image}" alt="${imageAlts[step.id]}"></div>
      </header>
      <div class="content-grid">
        <div class="main-stack">
          <section class="panel" aria-labelledby="actions-title"><h2 id="actions-title">Travail à faire</h2><ol class="action-list">${step.actions.map((a, i) => `<li><div class="question-text">${a}</div><p class="question-expectation"><strong>Attendu :</strong> ${step.actionExpectations[i]}</p></li>`).join("")}</ol></section>
          <section class="panel" aria-labelledby="resources-title"><h2 id="resources-title">Ressources et outils</h2><p>Choisissez uniquement les ressources utiles à votre problématique. Les conditions d’accès des outils peuvent évoluer.</p><div class="resource-grid">${resources(step.resources)}</div></section>
          <section class="panel transition-panel" aria-labelledby="transition-title"><h2 id="transition-title">Le lien avec la suite</h2><p>${step.transition}</p></section>
        </div>
        <aside class="side-stack">
          <section class="panel deliverable" aria-labelledby="deliverable-title"><h2 id="deliverable-title">À conserver pour le dossier</h2><p><strong>${step.deliverable}</strong></p><p>Pièce du dossier : <strong>${step.dossier}</strong></p></section>
        </aside>
      </div>
      <nav class="page-controls" aria-label="Navigation entre les étapes">${previous}${next}</nav>
    </article>
  </main>`;
}

const root = document.getElementById("step-root");
if (root) {
  const id = Number(document.body.dataset.step);
  const step = steps.find(s => s.id === id);
  if (step) {
    document.title = `Étape ${step.id} — ${step.title} | Mission veille IKEA`;
    root.outerHTML = renderStep(step);
  }
}
